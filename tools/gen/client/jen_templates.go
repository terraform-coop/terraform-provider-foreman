// Helper functions for framework resource generation

func hasList(fields []GenField) bool {
	for _, f := range fields {
		if f.IsList && f.GoType == "[]int64" {
			return true
		}
	}
	return false
}

func hasRawMessage(fields []GenField) bool {
	for _, f := range fields {
		if f.GoType == "json.RawMessage" {
			return true
		}
	}
	return false
}

func fieldInModel(fieldName string, entityFields []GenField) bool {
	for _, f := range entityFields {
		if f.GoName == fieldName {
			return true
		}
	}
	return false
}

func fieldIsComputed(fieldName string, requestFields []GenField, entityFields []GenField) bool {
	inEntity := false
	for _, f := range entityFields {
		if f.GoName == fieldName {
			inEntity = true
			break
		}
	}
	if !inEntity {
		return false
	}
	for _, f := range requestFields {
		if f.GoName == fieldName {
			return false
		}
	}
	return true
}

func fieldAccessor(fieldName string, fields []GenField, entityFields []GenField) jen.Code {
	var reqType, modelType string
	for _, f := range fields {
		if f.GoName == fieldName {
			reqType = f.GoType
			break
		}
	}
	for _, f := range entityFields {
		if f.GoName == fieldName {
			modelType = f.GoType
			break
		}
	}
	if reqType == modelType {
		switch reqType {
		case "string":
			return jen.Id("plan").Dot(fieldName).Dot("ValueString").Call()
		case "int64":
			return jen.Id("plan").Dot(fieldName).Dot("ValueInt64").Call()
		case "bool":
			return jen.Id("plan").Dot(fieldName).Dot("ValueBool").Call()
		}
	}
	// Mismatch: model is string, request is int64
	if modelType == "string" && reqType == "int64" {
		return jen.Func().Params().Int64().Block(
			jen.List(jen.Id("v"), jen.Id("_")).Op(":=").Qual("strconv", "ParseInt").Call(jen.Id("plan").Dot(fieldName).Dot("ValueString").Call(), jen.Lit(10), jen.Lit(64)),
			jen.Return(jen.Id("v")),
		).Call()
	}
	// Default: use model type
	switch modelType {
	case "string":
		return jen.Id("plan").Dot(fieldName).Dot("ValueString").Call()
	case "int64":
		return jen.Id("plan").Dot(fieldName).Dot("ValueInt64").Call()
	case "bool":
		return jen.Id("plan").Dot(fieldName).Dot("ValueBool").Call()
	}
	return jen.Id("plan").Dot(fieldName)
}

