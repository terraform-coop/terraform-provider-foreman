// generateRoundTripTestFile generates a round-trip test file for a resource using jen.
func generateRoundTripTestFile(res GenResource) *jen.File {
	f := jen.NewFile("generated")
	f.HeaderComment("Code generated by tools/gen/client/main.go. DO NOT EDIT.")

	// TestForemanXxx_RoundTrip
	f.Func().Id(fmt.Sprintf("Test%s_RoundTrip", res.GoName)).Params(jen.Id("t").Op("*").Qual("testing", "T")).BlockFunc(func(g *jen.Group) {
		g.Id("t").Dot("Parallel").Call()

		// original := &ForemanXxx{
		//   ForemanObject: ForemanObject{ID: 1, Name: "test"},
		//   Field1: "test_field1",
		//   ...
		// }
		g.Id("original").Op(":=").Op("&").Id(res.GoName).Values(jen.DictFunc(func(d jen.Dict) {
			d[jen.Id("ForemanObject")] = jen.Id("ForemanObject").Values(jen.Dict{
				jen.Id("ID"):   jen.Lit(1),
				jen.Id("Name"): jen.Lit("test"),
			})
			for _, field := range res.EntityFields {
				if field.IsList {
					continue
				}
				switch field.GoType {
				case "string":
					d[jen.Id(field.GoName)] = jen.Lit("test_" + field.JSONName)
				case "int64":
					d[jen.Id(field.GoName)] = jen.Lit(42)
				case "bool":
					d[jen.Id(field.GoName)] = jen.Lit(true)
				}
			}
		}))
		g.Line()

		// data, err := json.Marshal(original)
		g.List(jen.Id("data"), jen.Id("err")).Op(":=").Qual("encoding/json", "Marshal").Call(jen.Id("original"))
		g.Qual("github.com/stretchr/testify/require", "NoError").Call(jen.Id("t"), jen.Id("err"))
		g.Line()

		// var decoded ForemanXxx
		g.Var().Id("decoded").Id(res.GoName)
		g.Err().Op("=").Qual("encoding/json", "Unmarshal").Call(jen.Id("data"), jen.Op("&").Id("decoded"))
		g.Qual("github.com/stretchr/testify/require", "NoError").Call(jen.Id("t"), jen.Id("err"))
		g.Line()

		// assert.Equal(t, original.ID, decoded.ID)
		g.Qual("github.com/stretchr/testify/assert", "Equal").Call(jen.Id("t"), jen.Id("original").Dot("ID"), jen.Id("decoded").Dot("ID"))
		g.Qual("github.com/stretchr/testify/assert", "Equal").Call(jen.Id("t"), jen.Id("original").Dot("Name"), jen.Id("decoded").Dot("Name"))
		for _, field := range res.EntityFields {
			if field.IsList {
				continue
			}
			g.Qual("github.com/stretchr/testify/assert", "Equal").Call(jen.Id("t"), jen.Id("original").Dot(field.GoName), jen.Id("decoded").Dot(field.GoName))
		}
	})
	f.Line()

	// TestForemanXxx_RoundTripZeroValues
	f.Func().Id(fmt.Sprintf("Test%s_RoundTripZeroValues", res.GoName)).Params(jen.Id("t").Op("*").Qual("testing", "T")).BlockFunc(func(g *jen.Group) {
		g.Id("t").Dot("Parallel").Call()
		g.Id("original").Op(":=").Op("&").Id(res.GoName).Values()
		g.Line()

		g.List(jen.Id("data"), jen.Id("err")).Op(":=").Qual("encoding/json", "Marshal").Call(jen.Id("original"))
		g.Qual("github.com/stretchr/testify/require", "NoError").Call(jen.Id("t"), jen.Id("err"))
		g.Line()

		g.Var().Id("decoded").Id(res.GoName)
		g.Err().Op("=").Qual("encoding/json", "Unmarshal").Call(jen.Id("data"), jen.Op("&").Id("decoded"))
		g.Qual("github.com/stretchr/testify/require", "NoError").Call(jen.Id("t"), jen.Id("err"))
		g.Line()

		g.Qual("github.com/stretchr/testify/assert", "Equal").Call(jen.Id("t"), jen.Id("original").Dot("ID"), jen.Id("decoded").Dot("ID"))
		g.Qual("github.com/stretchr/testify/assert", "Equal").Call(jen.Id("t"), jen.Id("original").Dot("Name"), jen.Id("decoded").Dot("Name"))
		for _, field := range res.EntityFields {
			if field.IsList {
				continue
			}
			g.Qual("github.com/stretchr/testify/assert", "Equal").Call(jen.Id("t"), jen.Id("original").Dot(field.GoName), jen.Id("decoded").Dot(field.GoName))
		}
	})
	f.Line()

	// TestForemanXxx_RoundTripRequest
	f.Func().Id(fmt.Sprintf("Test%s_RoundTripRequest", res.GoName)).Params(jen.Id("t").Op("*").Qual("testing", "T")).BlockFunc(func(g *jen.Group) {
		g.Id("t").Dot("Parallel").Call()

		// original := &ForemanXxxRequest{
		//   Field1: "test_field1",
		//   ...
		// }
		g.Id("original").Op(":=").Op("&").Id(res.GoName + "Request").Values(jen.DictFunc(func(d jen.Dict) {
			for _, field := range res.Fields {
				if field.IsList {
					continue
				}
				switch field.GoType {
				case "string":
					d[jen.Id(field.GoName)] = jen.Lit("test_" + field.JSONName)
				case "int64":
					d[jen.Id(field.GoName)] = jen.Lit(42)
				case "bool":
					d[jen.Id(field.GoName)] = jen.Lit(true)
				}
			}
		}))
		g.Line()

		g.List(jen.Id("data"), jen.Id("err")).Op(":=").Qual("encoding/json", "Marshal").Call(jen.Id("original"))
		g.Qual("github.com/stretchr/testify/require", "NoError").Call(jen.Id("t"), jen.Id("err"))
		g.Line()

		g.Var().Id("decoded").Id(res.GoName + "Request")
		g.Err().Op("=").Qual("encoding/json", "Unmarshal").Call(jen.Id("data"), jen.Op("&").Id("decoded"))
		g.Qual("github.com/stretchr/testify/require", "NoError").Call(jen.Id("t"), jen.Id("err"))
		g.Line()

		for _, field := range res.Fields {
			if field.IsList {
				continue
			}
			g.Qual("github.com/stretchr/testify/assert", "Equal").Call(jen.Id("t"), jen.Id("original").Dot(field.GoName), jen.Id("decoded").Dot(field.GoName))
		}
	})
	f.Line()

	// TestForemanXxx_RoundTripRequestZeroValues
	f.Func().Id(fmt.Sprintf("Test%s_RoundTripRequestZeroValues", res.GoName)).Params(jen.Id("t").Op("*").Qual("testing", "T")).BlockFunc(func(g *jen.Group) {
		g.Id("t").Dot("Parallel").Call()
		g.Id("original").Op(":=").Op("&").Id(res.GoName + "Request").Values()
		g.Line()

		g.List(jen.Id("data"), jen.Id("err")).Op(":=").Qual("encoding/json", "Marshal").Call(jen.Id("original"))
		g.Qual("github.com/stretchr/testify/require", "NoError").Call(jen.Id("t"), jen.Id("err"))
		g.Line()

		g.Var().Id("decoded").Id(res.GoName + "Request")
		g.Err().Op("=").Qual("encoding/json", "Unmarshal").Call(jen.Id("data"), jen.Op("&").Id("decoded"))
		g.Qual("github.com/stretchr/testify/require", "NoError").Call(jen.Id("t"), jen.Id("err"))
		g.Line()

		for _, field := range res.Fields {
			if field.IsList {
				continue
			}
			g.Qual("github.com/stretchr/testify/assert", "Equal").Call(jen.Id("t"), jen.Id("original").Dot(field.GoName), jen.Id("decoded").Dot(field.GoName))
		}
	})

	return f
}

// generateFuzzTestFile generates the consolidated fuzz test file using jen.
func generateFuzzTestFile(resources []GenResource) *jen.File {
	f := jen.NewFile("generated")
	f.HeaderComment("Code generated by tools/gen/client/main.go. DO NOT EDIT.")

	f.Func().Id("FuzzForemanParseResponse").Params(jen.Id("f").Op("*").Qual("testing", "F")).BlockFunc(func(g *jen.Group) {
		g.Comment("Seed with valid empty JSON objects so fuzzer has a sane starting point.")
		g.Id("f").Dot("Add").Call(jen.Index().Byte().Parens(jen.Lit("{}")))
		g.Id("f").Dot("Add").Call(jen.Index().Byte().Parens(jen.Lit(`{"id":1,"name":"seed"}`)))
		g.Id("f").Dot("Add").Call(jen.Index().Byte().Parens(jen.Lit(`{"error":{"message":"boom"}}`)))
		g.Id("f").Dot("Add").Call(jen.Index().Byte().Parens(jen.Lit(`{"total":0,"page":1,"per_page":20,"results":[]}`)))
		g.Id("f").Dot("Add").Call(jen.Index().Byte().Parens(jen.Lit(`{"total":1,"page":1,"per_page":20,"results":[{"id":1,"name":"seed"}]}`)))
		g.Line()

		g.Id("f").Dot("Fuzz").Call(jen.Func().Params(jen.Id("t").Op("*").Qual("testing", "T"), jen.Id("data").Index().Byte()).BlockFunc(func(g *jen.Group) {
			g.For(jen.List(jen.Id("_"), jen.Id("target")).Op(":=").Range().Index().Interface().ValuesFunc(func(g *jen.Group) {
				for _, res := range resources {
					g.Op("&").Id(res.GoName).Values()
				}
			})).BlockFunc(func(g *jen.Group) {
				g.Id("_").Op("=").Qual("encoding/json", "Unmarshal").Call(jen.Id("data"), jen.Id("target"))
				g.Comment("must not panic")
			})
		}))
	})

	return f
}

// generateStatusCodeTestFile generates the consolidated status code test file using jen.
func generateStatusCodeTestFile(resources []GenResource) *jen.File {
	f := jen.NewFile("generated")
	f.HeaderComment("Code generated by tools/gen/client/main.go. DO NOT EDIT.")

	f.Func().Id("TestStatusCodes").Params(jen.Id("t").Op("*").Qual("testing", "T")).BlockFunc(func(g *jen.Group) {
		g.Id("t").Dot("Parallel").Call()
		g.Line()

		// codes := []struct{...}{...}
		g.Id("codes").Op(":=").Index().Struct(
			jen.Id("code").Int(),
			jen.Id("wantError").Bool(),
		).Values(
			jen.Values(jen.Lit(200), jen.False()),
			jen.Values(jen.Lit(201), jen.False()),
			jen.Values(jen.Lit(400), jen.True()),
			jen.Values(jen.Lit(401), jen.True()),
			jen.Values(jen.Lit(403), jen.True()),
			jen.Values(jen.Lit(404), jen.True()),
			jen.Values(jen.Lit(422), jen.True()),
			jen.Values(jen.Lit(500), jen.True()),
		)
		g.Line()

		// queryFuncs := []struct{...}{...}
		g.Id("queryFuncs").Op(":=").Index().Struct(
			jen.Id("name").String(),
			jen.Id("fn").Func().Params(jen.Op("*").Id("ForemanClient"), jen.Qual("context", "Context")).Error(),
		).ValuesFunc(func(g *jen.Group) {
			for _, res := range resources {
				if res.HasIndex {
					g.Values(jen.Dict{
						jen.Id("name"): jen.Lit(res.GoName),
						jen.Id("fn"): jen.Func().Params(jen.Id("c").Op("*").Id("ForemanClient"), jen.Id("ctx").Qual("context", "Context")).Error().Block(
							jen.List(jen.Id("_"), jen.Id("err")).Op(":=").Id("c").Dot("Query"+res.GoName).Call(jen.Id("ctx"), jen.Lit("test")),
							jen.Return(jen.Id("err")),
						),
					})
				}
			}
		})
		g.Line()

		// for _, qf := range queryFuncs {...}
		g.For(jen.List(jen.Id("_"), jen.Id("qf")).Op(":=").Range().Id("queryFuncs")).BlockFunc(func(g *jen.Group) {
			g.Id("qf").Op(":=").Id("qf")
			g.Id("t").Dot("Run").Call(jen.Id("qf").Dot("name"), jen.Func().Params(jen.Id("t").Op("*").Qual("testing", "T")).BlockFunc(func(g *jen.Group) {
				g.Id("t").Dot("Parallel").Call()
				g.For(jen.List(jen.Id("_"), jen.Id("tc")).Op(":=").Range().Id("codes")).BlockFunc(func(g *jen.Group) {
					g.Id("t").Dot("Run").Call(jen.Qual("net/http", "StatusText").Call(jen.Id("tc").Dot("code")), jen.Func().Params(jen.Id("t").Op("*").Qual("testing", "T")).BlockFunc(func(g *jen.Group) {
						g.Id("srv").Op(":=").Qual("net/http/httptest", "NewServer").Call(jen.Qual("net/http", "HandlerFunc").Call(jen.Func().Params(jen.Id("w").Qual("net/http", "ResponseWriter"), jen.Id("r").Op("*").Qual("net/http", "Request")).BlockFunc(func(g *jen.Group) {
							g.Id("w").Dot("WriteHeader").Call(jen.Id("tc").Dot("code"))
							g.If(jen.Op("!").Id("tc").Dot("wantError")).BlockFunc(func(g *jen.Group) {
								g.Qual("github.com/stretchr/testify/require", "NoError").Call(jen.Id("t"), jen.Qual("encoding/json", "NewEncoder").Call(jen.Id("w")).Dot("Encode").Call(jen.Map(jen.String()).Interface().Values()))
							}).Else().BlockFunc(func(g *jen.Group) {
								g.List(jen.Id("_"), jen.Id("err")).Op(":=").Qual("fmt", "Fprintf").Call(jen.Id("w"), jen.Lit(`{"error":{"message":"test error"}}`))
								g.Qual("github.com/stretchr/testify/require", "NoError").Call(jen.Id("t"), jen.Id("err"))
							})
						})))
						g.Defer().Id("srv").Dot("Close").Call()
						g.Line()

						g.Id("client").Op(":=").Id("NewClient").Call(
							jen.Id("parseURL").Call(jen.Id("srv").Dot("URL")),
							jen.Id("ClientCredentials").Values(),
							jen.Id("ClientConfig").Values(),
						)
						g.Line()

						g.Id("err").Op(":=").Id("qf").Dot("fn").Call(jen.Id("client"), jen.Qual("context", "Background").Call())
						g.If(jen.Id("tc").Dot("wantError")).Block(
							jen.Qual("github.com/stretchr/testify/assert", "Error").Call(jen.Id("t"), jen.Id("err")),
						).Else().Block(
							jen.Qual("github.com/stretchr/testify/assert", "NoError").Call(jen.Id("t"), jen.Id("err")),
						)
					}))
				})
			}))
		})
	})

	return f
}

